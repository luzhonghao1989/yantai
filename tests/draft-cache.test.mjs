import assert from 'node:assert/strict';
import {DraftCache} from '../frontend/src/draft-cache.ts';
import {localSettings} from '../frontend/src/local-settings.ts';

const records=new Map(),legacy=new Map();let puts=0;
const repository={get:async id=>records.get(id)||null,put:async p=>{puts++;await new Promise(r=>setTimeout(r,2));records.set(p.id,structuredClone(p));},remove:async id=>{records.delete(id);}};
const storage={getItem:key=>legacy.get(key)||null,removeItem:key=>legacy.delete(key)};
const cache=new DraftCache(repository,()=>storage);
const p={id:'novel',chapters:[{text:'第一稿'}],sources:[{text:'大'.repeat(3_000_000)}],revision:1};
assert(await cache.write(p));assert.equal((await cache.read(p.id)).sources[0].text.length,3_000_000);
assert.equal(legacy.size,0,'New drafts must not consume localStorage quota');
const first=cache.write({...p,chapters:[{text:'第二稿'}]});
const clear=cache.remove(p.id);
const last=cache.write({...p,chapters:[{text:'保存期间继续编辑'}]});
await Promise.all([first,clear,last]);assert.equal((await cache.read(p.id)).chapters[0].text,'保存期间继续编辑');
await cache.remove(p.id);assert.equal(await cache.read(p.id),null);
legacy.set('draft:novel',JSON.stringify({...p,sources:[]}));assert.equal((await cache.read(p.id)).chapters[0].text,'第一稿');
await cache.write({...p,sources:[]});assert(!legacy.has('draft:novel'),'Old recovery cache migrates after successful IDB write');
const denied={get:async()=>{throw Error('denied')},put:async()=>{throw Error('quota')},remove:async()=>{throw Error('denied')}};
const unavailable=new DraftCache(denied,()=>{throw Error('storage disabled')});
assert.equal(await unavailable.write(p),false);await unavailable.remove(p.id);assert.equal(await unavailable.read(p.id),null);
const fallback=new DraftCache(denied,()=>storage);legacy.set('draft:novel',JSON.stringify({...p,sources:[]}));
assert.equal((await fallback.read(p.id)).id,p.id);assert.equal(await fallback.write(p),false);assert(legacy.has('draft:novel'));
legacy.set('draft:novel','{broken');assert.equal(await fallback.read(p.id),null);
legacy.set('draft:novel',JSON.stringify({id:'wrong',chapters:[]}));assert.equal(await fallback.read(p.id),null);
assert(await cache.write({...p,sources:[]}), 'Cache continues after an earlier failure');assert(puts>=5);
globalThis.window={get localStorage(){throw Error('Storage disabled')}};
assert.equal(localSettings.getItem('theme'),null);assert.doesNotThrow(()=>localSettings.setItem('cursor','1'));assert.doesNotThrow(()=>localSettings.removeItem('old'));
delete globalThis.window;
console.log('Draft recovery: large drafts outside localStorage, ordered write/clear, edits during save, legacy recovery/migration, quota/permission failures and safe preferences passed');
