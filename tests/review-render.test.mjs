import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {pathToFileURL} from 'node:url';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {build}=require('esbuild'),React=require('react'),{renderToStaticMarkup}=require('react-dom/server');
const outfile=resolve('frontend/node_modules/.cache/yantai-review-result.mjs');
await mkdir(dirname(outfile),{recursive:true});
await build({entryPoints:[resolve('frontend/src/ReviewResult.tsx')],outfile,bundle:true,platform:'node',format:'esm',jsx:'automatic',packages:'external',logLevel:'silent'});
const {default:ReviewResult}=await import(pathToFileURL(outfile).href);
const render=text=>renderToStaticMarkup(React.createElement(ReviewResult,{text,onGenerate:()=>{},onReplace:()=>{}}));
const malformed='{"summary":"请保留这份已经返回的审稿意见","suggestions":[';
let html=render(malformed);
assert(html.includes('请保留这份已经返回的审稿意见'),'Malformed JSON must not hide the completed report');
assert(html.includes('按审稿意见生成修改段落'));
assert(!html.includes('暂时无法生成可替换段落，请重新生成'));
html=render('以下是审稿结果：\n```json '+JSON.stringify({result:{summary:'对白可以更自然。',suggestions:[{original:'她说你好。',replacement:'她看着他：“来了？”',reason:'加上动作。'}]}})+'```');
assert(html.includes('对白可以更自然。'));assert(html.includes('建议段落'));assert(html.includes('加上动作。'));
assert(!html.includes('暂未提取到可替换的完整段落'));
html=render('这是普通的历史审稿意见。');assert(html.includes('这是普通的历史审稿意见。'));
console.log('Review rendering: malformed and legacy content stays readable; wrapped structured reviews render suggestions passed');
